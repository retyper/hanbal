/** 이 경위도가 뭍(또는 섬) 위인가 */
export function onSouthLand(lon: number, lat: number): boolean {
  const p: LL = [lon, lat]
  return SOUTH_LANDS.some((l) => inside(p, l)) || SOUTH_ISLES.some((l) => inside(p, l))
}

