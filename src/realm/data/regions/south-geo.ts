/** 경위도 → 판 위 비율 */
export function southPos(lon: number, lat: number): readonly [number, number] {
  const P = SOUTH_PROJ
  return [(lon - P.lon0) / (P.lon1 - P.lon0), (P.lat1 - lat) / (P.lat1 - P.lat0)]
}

