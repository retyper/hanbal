/** 이 장수가 사서에 남은 사람이면 그 이야기 — 지어낸 사람이면 undefined */
export function annalOf(heroId: string): Annal | undefined {
  const k = ANNAL_OF[heroId]
  return k !== undefined ? ANNALS[k] : undefined
}
