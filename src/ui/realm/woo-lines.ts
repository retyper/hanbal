export function wooKneelLine(r: Realm, _by: Hero, x: Hero, _talk: readonly WooApproach[], reacts: readonly WooReact[]): string {
  const last = reacts[reacts.length - 1]
  const refused = last !== undefined && okOf(last) === 'no'
  const held = heldOf(r, x)
  if (held !== null) return held.yield[refused ? 'refused' : 'agreed']
  return (refused ? KNEEL_AFTER_NO : KNEEL)[kindOf(x)]
}

/** 본말의 첫 문장 (지문 괄호는 뺀다) — 넘어온 한 줄에 인용한다 */
const sentences = (s: string): string[] => s.replace(/\([^)]*\)\s*/g, '').trim().split(/(?<=[.!?…])\s+/).filter((y) => y !== '')
/** 인용할 한 문장 — 명분 · 인연은 내세운 사실의 첫 문장, 다른 거리는 본말에서 가장 긴 문장 (「좋소, 더 얹겠소!」 같은 잇는 말보다 알맹이) */
export function keySentence(p: { body: string; fact: string }): string {
  const pick = p.fact !== '' ? sentences(p.fact).slice(0, 1) : sentences(p.body)
  return pick.reduce((a, b) => (b.length >= a.length ? b : a), '').replace(/[.]$/, '')
}
/** 넘어왔다 — 판을 가른 말을 인용한다 (마지막으로 먹힌 마디, 없으면 마지막 마디) */
export function wooWonLine(r: Realm, by: Hero, x: Hero, talk: readonly WooApproach[], reacts: readonly WooReact[]): string {
  let i = reacts.length - 1
  for (let j = reacts.length - 1; j >= 0; j--) if (reacts[j] === 'big' || reacts[j] === 'sway') { i = j; break }
  const tail = `${josa(by.name, '의', '의')} 이 한마디에 ${josa(x.name, '이', '가')} 무릎을 꿇었다`
  if (i < 0 || talk[i] === undefined) return tail
  return `「${keySentence(pitchParts(r, by, x, talk, i, reacts))}」 ${tail}`
}
