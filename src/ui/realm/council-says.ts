/** 조사 짝 — {이름|은} 의 '은' 이 무엇과 짝인가 (으로는 · 이면 은 앞 조사를 받침으로 가른다) */
const PAIR: Readonly<Record<string, readonly [string, string]>> = {
  은: ['은', '는'], 이: ['이', '가'], 을: ['을', '를'], 으로: ['으로', '로'], 과: ['과', '와'], 으로는: ['으로는', '로는'], 이면: ['이면', '면'],
}

/** 말 틀을 채운다 — {이름} · {이름|조사} */
export function fill(t: string, v: Readonly<Record<string, string>>): string {
  return t.replace(/\{(\w+)(?:\|([^}]+))?\}/g, (_, k: string, p: string | undefined) => {
    const w = v[k] ?? ''
    if (p === undefined) return w
    const pr = PAIR[p]
    return pr === undefined ? w + p : josa(w, pr[0], pr[1])
  })
}

/** 고르는 굴림 — 장수·처지·계절로 정해진다 (같은 판 같은 계절이면 같은 말 · 계절마다 바뀐다) */
export function pickIdx(key: string, n: number): number {
  let s = 2166136261
  for (let i = 0; i < key.length; i++) s = Math.imul(s ^ key.charCodeAt(i), 16777619) >>> 0
  return n <= 0 ? 0 : s % n
}

/**
 * 사극 말투 — 신하가 군주에게 아뢰는 끝 (형 10-29: "~하옵니다 · ~하겠사옵니다 · ~지요, 이런 사극 말투를 왜 안 함").
 * 「-습니다 → -사옵니다」 · 「-ㅂ니다 → -옵니다(받침 ㅂ을 떼고)」 · 「-십시오 → -시옵소서」 · -시지요 는 그대로
 */
export function sageuk(s: string): string {
  return s
    .replace(/겁니다/g, '것입니다')
    .replace(/습니다/g, '사옵니다')
    .replace(/([가-힣])니다/g, (m: string, c: string) => {
      const code = c.charCodeAt(0) - 0xac00
      if (code < 0 || code % 28 !== 17 || c === '옵') return m // 받침이 ㅂ 인 글자만 (이미 바꾼 '옵'은 그대로)
      return String.fromCharCode(c.charCodeAt(0) - 17) + '옵니다'
    })
    .replace(/십시오/g, '시옵소서')
}

/** 이 장수가 이 처지에서 할 말 — 결의 말과 특성의 말 가운데 하나 (특성 말은 두 번 넣어 더 자주) */
export function sayOf(h: Hero, move: Move, v: Readonly<Record<string, string>>, season: number): string {
  const pool: string[] = [...SAYS[voiceKind(h)][move]]
  for (const t of h.traits) {
    const ts = TRAIT_SAYS[t]?.[move]
    if (ts !== undefined && hasTrait(h, t)) pool.push(...ts, ...ts)
  }
  return sageuk(fill(pool[pickIdx(`${h.id}:${move}:${season}`, pool.length)]!, v))
}
