// eslint-disable-next-line no-unused-vars
function tileSketch(T, W = 1024, H = 765) {
  const X = (lon) => ((lon - T.lon0) / (T.lon1 - T.lon0)) * W
  const Y = (lat) => ((T.lat1 - lat) / (T.lat1 - T.lat0)) * H
  const c = document.createElement('canvas')
  c.width = W
  c.height = H
  const g = c.getContext('2d')
  g.fillStyle = '#8fb3c9'
  g.fillRect(0, 0, W, H)
  const poly = (pts) => {
    g.beginPath()
    pts.forEach(([lo, la], i) => (i === 0 ? g.moveTo(X(lo), Y(la)) : g.lineTo(X(lo), Y(la))))
    g.closePath()
    g.fillStyle = '#e9dcb8'
    g.fill()
    g.strokeStyle = '#3a2a1a'
    g.lineWidth = 3
    g.stroke()
  }
  poly(T.land)
  for (const p of T.more ?? []) poly(p)
  for (const p of T.isles) poly(p)
  for (const p of T.lakes ?? []) {
    g.beginPath()
    p.forEach(([lo, la], i) => (i === 0 ? g.moveTo(X(lo), Y(la)) : g.lineTo(X(lo), Y(la))))
    g.closePath()
    g.fillStyle = '#8fb3c9'
    g.fill()
  }
  g.fillStyle = '#5f7f45'
  for (const [lo0, lo1, la0, la1, n, seed] of T.peaks) {
    let s = seed
    const rnd = () => ((s = (s * 1103515245 + 12345) % 2147483648) / 2147483648)
    for (let i = 0; i < n; i++) {
      const x = X(lo0 + rnd() * (lo1 - lo0))
      const y = Y(la0 + rnd() * (la1 - la0))
      g.beginPath(); g.moveTo(x, y - 14); g.lineTo(x - 11, y + 8); g.lineTo(x + 11, y + 8); g.closePath(); g.fill()
    }
  }
  for (const [pts, w] of T.rivers) {
    g.beginPath()
    pts.forEach(([lo, la], i) => (i === 0 ? g.moveTo(X(lo), Y(la)) : g.lineTo(X(lo), Y(la))))
    g.strokeStyle = '#3d6f9a'; g.lineWidth = w; g.lineJoin = 'round'; g.lineCap = 'round'; g.stroke()
  }
  return c
}
