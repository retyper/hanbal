/**
 * 영남 판 지도의 밑그림 — 실제 경위도로 그린 해안선·강·산줄기 (형: "지도랑 비슷하게 일치시키던지").
 * 브라우저에서 돌려 PNG 로 만든다 → 제미나이에 "이 밑그림 그대로 옛 지도로 그려 달라"고 맡긴다.
 * 같은 투영(PROJ)을 판 데이터의 고을 자리(NODE_POS)에도 쓴다 — 그래서 그림과 자리가 맞는다.
 *
 * 쓰는 법: 브라우저 콘솔에서 이 파일 내용을 붙여 넣고 `yeongnamSketch()` → canvas 를 돌려준다.
 */
// eslint-disable-next-line no-unused-vars
function yeongnamSketch(W = 1536, H = 1152) {
  const PROJ = { lon0: 127.4, lon1: 130.3, lat0: 34.55, lat1: 36.55 }
  const X = (lon) => ((lon - PROJ.lon0) / (PROJ.lon1 - PROJ.lon0)) * W
  const Y = (lat) => ((PROJ.lat1 - lat) / (PROJ.lat1 - PROJ.lat0)) * H
  const c = document.createElement('canvas')
  c.width = W
  c.height = H
  const g = c.getContext('2d')
  g.fillStyle = '#8fb3c9' // 바다
  g.fillRect(0, 0, W, H)
  const poly = (pts, fill, stroke) => {
    g.beginPath()
    pts.forEach(([lo, la], i) => (i === 0 ? g.moveTo(X(lo), Y(la)) : g.lineTo(X(lo), Y(la))))
    g.closePath()
    g.fillStyle = fill
    g.fill()
    if (stroke) { g.strokeStyle = stroke; g.lineWidth = 3; g.stroke() }
  }
  const LAND = [
    [127.2, 36.7], [129.42, 36.7], [129.43, 36.4], [129.42, 36.2], [129.41, 36.1], [129.36, 36.02], [129.45, 36.0], [129.57, 36.08],
    [129.5, 35.95], [129.46, 35.8], [129.47, 35.65], [129.42, 35.52], [129.36, 35.48], [129.35, 35.36], [129.26, 35.25], [129.17, 35.16],
    [129.08, 35.08], [128.99, 35.05], [128.95, 35.09], [128.86, 35.07], [128.76, 35.08], [128.7, 35.13], [128.6, 35.19], [128.56, 35.1],
    [128.46, 35.03], [128.43, 34.92], [128.34, 34.95], [128.26, 34.93], [128.17, 34.94], [128.08, 35.02], [127.99, 34.96], [127.88, 34.96],
    [127.78, 34.98], [127.7, 34.95], [127.6, 34.93], [127.45, 34.86], [127.2, 34.86],
  ]
  poly(LAND, '#e9dcb8', '#3a2a1a')
  const ISLES = [
    [[128.47, 35.0], [128.62, 35.03], [128.73, 34.95], [128.7, 34.82], [128.6, 34.72], [128.52, 34.8], [128.45, 34.9]], // 거제
    [[127.82, 34.9], [127.95, 34.93], [128.06, 34.85], [128.02, 34.72], [127.88, 34.7], [127.8, 34.78]], // 남해
    [[128.86, 35.06], [128.9, 35.06], [128.9, 35.02], [128.85, 35.02]], // 가덕
    [[128.3, 34.82], [128.36, 34.83], [128.36, 34.78], [128.3, 34.78]],
    [[128.18, 34.85], [128.23, 34.86], [128.22, 34.81]],
  ]
  for (const p of ISLES) poly(p, '#e9dcb8', '#3a2a1a')
  // 산줄기 — 작은 세모
  g.fillStyle = '#5f7f45'
  const peaks = (lo0, lo1, la0, la1, n, seed) => {
    let s = seed
    const rnd = () => ((s = (s * 1103515245 + 12345) % 2147483648) / 2147483648)
    for (let i = 0; i < n; i++) {
      const lo = lo0 + rnd() * (lo1 - lo0)
      const la = la0 + rnd() * (la1 - la0)
      const x = X(lo)
      const y = Y(la)
      g.beginPath()
      g.moveTo(x, y - 14)
      g.lineTo(x - 11, y + 8)
      g.lineTo(x + 11, y + 8)
      g.closePath()
      g.fill()
    }
  }
  peaks(127.3, 127.95, 35.1, 36.7, 220, 7) // 소백 — 서쪽 가장자리 (지리산 · 덕유산 · 가야산 쪽)
  peaks(128.0, 128.25, 35.6, 36.0, 40, 11) // 가야산
  peaks(128.95, 129.3, 35.6, 36.7, 140, 13) // 태백 줄기 — 동해 쪽
  peaks(128.95, 129.15, 35.4, 35.65, 40, 17) // 가지산 · 영남 알프스
  peaks(128.5, 128.85, 36.0, 36.7, 70, 19) // 북쪽 구릉 (팔공산 · 의성)
  // 강
  const river = (pts, w) => {
    g.beginPath()
    pts.forEach(([lo, la], i) => (i === 0 ? g.moveTo(X(lo), Y(la)) : g.lineTo(X(lo), Y(la))))
    g.strokeStyle = '#3d6f9a'
    g.lineWidth = w
    g.lineJoin = 'round'
    g.lineCap = 'round'
    g.stroke()
  }
  river([[128.1, 36.7], [128.2, 36.42], [128.33, 36.2], [128.38, 36.0], [128.45, 35.85], [128.4, 35.7], [128.43, 35.55], [128.45, 35.4], [128.6, 35.38], [128.78, 35.4], [128.88, 35.3], [128.95, 35.1]], 9) // 낙동강
  river([[127.7, 35.42], [127.9, 35.25], [128.08, 35.18], [128.25, 35.27], [128.4, 35.36], [128.45, 35.4]], 6) // 남강
  river([[128.95, 36.0], [128.75, 35.93], [128.55, 35.88], [128.45, 35.85]], 5) // 금호강
  river([[127.95, 35.6], [128.15, 35.56], [128.3, 35.55], [128.42, 35.55]], 4) // 황강
  river([[129.2, 35.7], [129.22, 35.85], [129.3, 35.96], [129.37, 36.03]], 4) // 형산강
  river([[129.1, 35.56], [129.3, 35.55], [129.37, 35.5]], 4) // 태화강
  river([[128.9, 35.62], [128.78, 35.5], [128.75, 35.4]], 4) // 밀양강
  river([[128.62, 36.55], [128.42, 36.45], [128.25, 36.42]], 4) // 위천 · 내성천 쪽
  return c
}
