"""Bake and install only individually reviewed first-awakening sprite sheets."""
from pathlib import Path
import json, shutil, importlib.util, argparse
ROOT=Path(__file__).resolve().parents[3]; HERE=Path(__file__).parent
import sys
sys.dont_write_bytecode = True
sys.path.insert(0, str(HERE.parent))
from manifest_ts import MANIFEST_IMPORT, manifest_expression
parser=argparse.ArgumentParser();parser.add_argument('keys',nargs='*');args=parser.parse_args()
queue=json.loads((HERE/'queue.json').read_text('utf8'))
s=importlib.util.spec_from_file_location('full20',HERE.parent/'bake-full20.py');m=importlib.util.module_from_spec(s);s.loader.exec_module(m);m.HERE=HERE
dest=HERE.parent/'repairs/20261113';reports=json.loads((dest/'repair-report.json').read_text('utf8'))
specpath=HERE.parent/'repair-pilot.json';specs=json.loads(specpath.read_text('utf8'))
for key in args.keys:
 j=next(x for x in queue if x['key']==key)
 assert j.get('review')=='accepted' and j.get('proportionReviewed') is True,'Manual full20 and baseline review required'
 report=m.bake(HERE/'candidates',key)
 for name in [f'gen-{key}.png',f'duel-{key}.png',f'{key}-report.json']:shutil.copy2(HERE/'candidates'/name,dest/name)
 reports[key]=report;specs[key]={'pipeline':'awakened20-master'}
 j.update(status='installed',report=str((HERE/'candidates'/f'{key}-report.json').relative_to(ROOT)))
 print('Installed',key,report['cell'])
(dest/'repair-report.json').write_text(json.dumps(reports,indent=2),encoding='utf8')
specpath.write_text(json.dumps(specs,indent=2),encoding='utf8')
(HERE/'queue.json').write_text(json.dumps(queue,ensure_ascii=False,indent=2),encoding='utf8')
installed=[j for j in queue if j['status']=='installed']
maps={
 'AWAKENED_BY_BASE':({j['baseKey']:j['key'] for j in installed},'Readonly<Record<string,string>>'),
 'AWAKENED_ANIM':({j['key']:dict(ar=reports[j['key']]['cell'][0]/160,body=reports[j['key']]['bodyPx']/160,**({'bow':True} if j['weapon']=='bow' else {})) for j in installed},'Readonly<Record<string,{ar:number;body:number;bow?:true}>>'),
 'AWAKENED_ATLASES':({j['key']:reports[j['key']]['duelAtlas'] for j in installed},''),
 'AWAKENED_CONTACT':({'gen-'+j['key']:reports[j['key']]['contact'] for j in installed},'Readonly<Record<string,[number,number,number]>>'),
 'AWAKENED_HEAVY':([j['key'] for j in installed if j['weapon']=='heavy'],''),
 'AWAKENED_BLADE':([j['key'] for j in installed if j['weapon'] in ['sword','sickle']],''),
}
text='/** Reviewed first-awakening battle sprites. Generated by awakened-20261114/install.py. */\n'+MANIFEST_IMPORT
for name,(value,typ) in maps.items():text+='export const '+name+(': '+typ if typ else '')+' = '+(manifest_expression(value) if name == 'AWAKENED_ATLASES' else json.dumps(value))+'\n'
(ROOT/'src/realm/data/awakenedSpritesGenerated.ts').write_text(text,encoding='utf8')
