/**
 * 마한(전라) 쪽 지도 조각의 밑그림 — 영남 판(tools/yeongnam-sketch.js)과 같은 눈금으로 서쪽에 붙는 조각.
 * 형 (2026-10-19): "지도를 … 부분부분 만든걸 합쳐가지고 시간지나서 발견국가가 많아지면 확장하는거지 지도도."
 *
 * 세계 눈금: 조각 하나 = 경도 2.9° × 위도 2.0° = 1024×765. 영남 조각 lon 127.4–130.3 · lat 34.55–36.55.
 * 이 조각은 lon 124.8–127.7 — 영남과 0.3°(106px) 겹친다. 이어 붙일 때 겹친 띠를 부드럽게 섞는다.
 * 브라우저 콘솔에 붙여 넣고 `mahanSketch()` → canvas.
 */
// eslint-disable-next-line no-unused-vars
function mahanSketch(W = 1024, H = 765) {
  const PROJ = { lon0: 124.8, lon1: 127.7, lat0: 34.55, lat1: 36.55 }
  const X = (lon) => ((lon - PROJ.lon0) / (PROJ.lon1 - PROJ.lon0)) * W
  const Y = (lat) => ((PROJ.lat1 - lat) / (PROJ.lat1 - PROJ.lat0)) * H
  const c = document.createElement('canvas')
  c.width = W
  c.height = H
  const g = c.getContext('2d')
  g.fillStyle = '#8fb3c9'
  g.fillRect(0, 0, W, H)
  const poly = (pts, fill, stroke) => {
    g.beginPath()
    pts.forEach(([lo, la], i) => (i === 0 ? g.moveTo(X(lo), Y(la)) : g.lineTo(X(lo), Y(la))))
    g.closePath()
    g.fillStyle = fill
    g.fill()
    if (stroke) { g.strokeStyle = stroke; g.lineWidth = 3; g.stroke() }
  }
  // 서해안(북→남) · 남해안(서→동) · 동쪽은 영남과 겹치는 띠
  const LAND = [
    [126.45, 36.7], [126.5, 36.5], [126.55, 36.35], [126.6, 36.12], [126.68, 36.0], [126.6, 35.92], [126.5, 35.82], [126.47, 35.7],
    [126.5, 35.62], [126.62, 35.56], [126.5, 35.48], [126.4, 35.32], [126.35, 35.15], [126.42, 35.02], [126.36, 34.88], [126.42, 34.78],
    [126.38, 34.62], [126.45, 34.5], [126.62, 34.45], [126.75, 34.56], [126.85, 34.62], [126.98, 34.55], [127.12, 34.62], [127.25, 34.55],
    [127.38, 34.7], [127.5, 34.85], [127.6, 34.93], [127.7, 34.95], [127.8, 34.9], [127.8, 36.7],
  ]
  poly(LAND, '#e9dcb8', '#3a2a1a')
  const ISLES = [
    [[126.38, 35.84], [126.44, 35.84], [126.43, 35.79], [126.37, 35.8]], // 고군산
    [[126.27, 35.62], [126.33, 35.62], [126.32, 35.58], [126.26, 35.58]], // 위도
    [[126.05, 35.0], [126.2, 35.05], [126.25, 34.92], [126.12, 34.85], [126.03, 34.9]], // 신안 섬들
    [[126.15, 34.8], [126.3, 34.78], [126.28, 34.68], [126.16, 34.68]],
    [[126.0, 34.72], [126.08, 34.72], [126.08, 34.65], [126.0, 34.65]],
    [[125.38, 34.7], [125.47, 34.7], [125.46, 34.64], [125.38, 34.64]], // 흑산
    [[126.18, 34.55], [126.4, 34.58], [126.42, 34.4], [126.2, 34.4]], // 진도
    [[126.68, 34.4], [126.82, 34.45], [126.85, 34.35], [126.7, 34.33]], // 완도 쪽
    [[127.2, 34.5], [127.4, 34.55], [127.42, 34.45], [127.25, 34.42]], // 고흥 앞 섬
  ]
  for (const p of ISLES) poly(p, '#e9dcb8', '#3a2a1a')
  g.fillStyle = '#5f7f45'
  const peaks = (lo0, lo1, la0, la1, n, seed) => {
    let s = seed
    const rnd = () => ((s = (s * 1103515245 + 12345) % 2147483648) / 2147483648)
    for (let i = 0; i < n; i++) {
      const x = X(lo0 + rnd() * (lo1 - lo0))
      const y = Y(la0 + rnd() * (la1 - la0))
      g.beginPath(); g.moveTo(x, y - 14); g.lineTo(x - 11, y + 8); g.lineTo(x + 11, y + 8); g.closePath(); g.fill()
    }
  }
  peaks(127.35, 127.8, 35.1, 36.7, 150, 23) // 소백 서쪽 자락 · 지리산 · 덕유산 (영남 조각과 이어진다)
  peaks(126.9, 127.35, 35.35, 35.9, 70, 29) // 노령 · 내장산
  peaks(126.85, 127.1, 35.05, 35.25, 30, 31) // 무등산
  peaks(126.95, 127.3, 34.7, 35.0, 40, 37) // 남쪽 구릉 (보성 · 장흥)
  peaks(126.5, 126.6, 35.58, 35.68, 10, 41) // 변산
  const river = (pts, w) => {
    g.beginPath()
    pts.forEach(([lo, la], i) => (i === 0 ? g.moveTo(X(lo), Y(la)) : g.lineTo(X(lo), Y(la))))
    g.strokeStyle = '#3d6f9a'; g.lineWidth = w; g.lineJoin = 'round'; g.lineCap = 'round'; g.stroke()
  }
  river([[127.45, 36.4], [127.2, 36.25], [126.95, 36.25], [126.8, 36.08], [126.68, 36.0]], 8) // 금강
  river([[127.2, 35.92], [126.95, 35.86], [126.72, 35.88], [126.55, 35.85]], 5) // 만경강
  river([[126.98, 35.68], [126.75, 35.74], [126.6, 35.74]], 4) // 동진강
  river([[126.98, 35.28], [126.82, 35.05], [126.6, 34.88], [126.42, 34.8]], 6) // 영산강
  river([[127.3, 35.78], [127.25, 35.45], [127.4, 35.2], [127.6, 35.05], [127.7, 34.95]], 6) // 섬진강
  return c
}
